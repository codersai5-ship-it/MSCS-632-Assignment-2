// C++: Type System Example
#include <iostream>
#include <string>
using namespace std;

int main() {
    int wholeNumber = 10;
    string text = "Hello";
    double decimalNumber = 10.5;

    cout << "Integer value: " << wholeNumber << endl;
    cout << "String value: " << text << endl;
    cout << "Double value: " << decimalNumber << endl;

    return 0;
}
